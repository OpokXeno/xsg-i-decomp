        void closeLopenR() {
            this.setRotate(0.0f, 0.0f, 0.0f);
            int n = 0;
            while (n < 60) {
                this.getTranslate();
                this.setTranslate(this.px + 0.033333335f, this.py, this.pz);
                System.sleep(1);
                ++n;
            }
        }

        void openLcloseR() {
            this.setRotate(0.0f, 0.0f, 0.0f);
            int n = 0;
            while (n < 60) {
                this.getTranslate();
                this.setTranslate(this.px - 0.033333335f, this.py, this.pz);
                System.sleep(1);
                ++n;
            }
        }

        void return_prop() {
            this.setTranslate(0.0f, 0.0f, 0.0f);
        }

        void rotate_sora() {
            this.setTranslate(0.0f, 0.0f, 0.0f);
            this.setRotateY(0.0f);
            while (true) {
                this.setRotateY(this.ry + 0.015f);
                System.sleep(1);
            }
        }
